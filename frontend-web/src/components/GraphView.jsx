import React, { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import ReactFlow, {
  Background,
  Controls,
  MiniMap,
  ReactFlowProvider,
  useEdgesState,
  useNodesState,
  useReactFlow,
} from 'reactflow';
import 'reactflow/dist/style.css';
import {
  GitFork,
  RefreshCw,
  UploadCloud,
  Maximize2,
  Minimize2,
  Lock,
  Unlock,
  Move,
  LayoutGrid,
  Info,
  Compass,
  Network,
} from 'lucide-react';

const VALID_ASSESSMENTS = new Set(['MATCH', 'CONTRADICTION', 'INDETERMINATE']);

function getAssessmentStatus(node) {
  // Legacy boolean flags may have been generated by the retired uncalibrated
  // Sinkhorn threshold. Never reinterpret them as a classifier assessment.
  const status = String(node?.data?.assessment_status || '').toUpperCase();
  return VALID_ASSESSMENTS.has(status) ? status : 'INDETERMINATE';
}

const STATUS_PRESENTATION = {
  MATCH: {
    label: 'MATCH',
    text: 'text-emerald-300',
    border: 'border-emerald-700',
    background: 'bg-emerald-950/80',
    dot: '#34d399',
  },
  CONTRADICTION: {
    label: 'CONTRADICTION',
    text: 'text-red-300',
    border: 'border-red-700',
    background: 'bg-red-950/80',
    dot: '#f87171',
  },
  INDETERMINATE: {
    label: 'INDETERMINATE',
    text: 'text-slate-300',
    border: 'border-slate-600',
    background: 'bg-slate-800/90',
    dot: '#94a3b8',
  },
};

function FlowInner({
  nodes: propNodes = [],
  edges: propEdges = [],
  onRefresh,
  fullScreenMode = false,
  toggleFullScreen,
  isMultiCaseView = false,
  cases = [],
  onSelectCase,
}) {
  const sourceNodes = Array.isArray(propNodes) ? propNodes : [];
  const sourceEdges = Array.isArray(propEdges) ? propEdges : [];
  const [nodes, setNodes, onNodesChange] = useNodesState(sourceNodes);
  const [edges, setEdges, onEdgesChange] = useEdgesState(sourceEdges);
  const [isLocked, setIsLocked] = useState(false);
  const [selectedNodeInfo, setSelectedNodeInfo] = useState(null);
  const [hoveredNode, setHoveredNode] = useState(null);
  const [mousePos, setMousePos] = useState({ x: 0, y: 0 });
  const [spreadStep, setSpreadStep] = useState(0);
  const [caseFilter, setCaseFilter] = useState('ALL');
  const reactFlowInstance = useReactFlow();
  const containerRef = useRef(null);
  const fitTimerRef = useRef(null);

  const filteredGraph = useMemo(() => {
    if (caseFilter === 'ALL') return { nodes: sourceNodes, edges: sourceEdges };
    const filteredNodes = sourceNodes.filter((node) => node.data?.case_id === caseFilter);
    const visibleIds = new Set(filteredNodes.map((node) => node.id));
    const filteredEdges = sourceEdges.filter(
      (edge) => visibleIds.has(edge.source) && visibleIds.has(edge.target),
    );
    return { nodes: filteredNodes, edges: filteredEdges };
  }, [sourceNodes, sourceEdges, caseFilter]);

  // Include content, status, style, and position in the signature. Stable IDs
  // alone are insufficient because an existing pair can be re-assessed.
  const graphSignature = useMemo(
    () => JSON.stringify({ nodes: filteredGraph.nodes, edges: filteredGraph.edges }),
    [filteredGraph],
  );
  const lastSyncKey = useRef('');

  useEffect(() => {
    if (graphSignature === lastSyncKey.current) return;
    lastSyncKey.current = graphSignature;

    const enhancedNodes = filteredGraph.nodes.map((node) => ({
      ...node,
      draggable: !isLocked,
      data: {
        ...node.data,
        title: node.data?.full_text || node.data?.label || '',
      },
      style: {
        ...node.style,
        cursor: isLocked ? 'default' : 'grab',
      },
    }));
    const enhancedEdges = filteredGraph.edges.map((edge) => ({
      ...edge,
      labelStyle: { fill: '#f1f5f9', fontWeight: 600, fontSize: 11 },
      labelBgStyle: { fill: '#0f172a', fillOpacity: 0.95, stroke: '#334155', strokeWidth: 1 },
      labelBgPadding: [6, 4],
      labelBgBorderRadius: 6,
    }));

    setNodes(enhancedNodes);
    setEdges(enhancedEdges);
    setSelectedNodeInfo((current) => (
      current ? enhancedNodes.find((node) => node.id === current.id) || null : null
    ));
    setHoveredNode(null);

    if (fitTimerRef.current) window.clearTimeout(fitTimerRef.current);
    if (enhancedNodes.length > 0) {
      fitTimerRef.current = window.setTimeout(() => {
        try {
          reactFlowInstance.fitView({ padding: 0.25, duration: 350 });
        } catch (error) {
          // React Flow may not be measurable during the first render.
        }
      }, 60);
    }
  }, [graphSignature, filteredGraph, isLocked, reactFlowInstance, setEdges, setNodes]);

  useEffect(() => () => {
    if (fitTimerRef.current) window.clearTimeout(fitTimerRef.current);
  }, []);

  // Lock/unlock must update current React Flow nodes without forcing a graph
  // resynchronization or discarding the investigator's manual layout.
  useEffect(() => {
    setNodes((current) => current.map((node) => ({
      ...node,
      draggable: !isLocked,
      style: { ...node.style, cursor: isLocked ? 'default' : 'grab' },
    })));
  }, [isLocked, setNodes]);

  useEffect(() => {
    if (!isMultiCaseView && caseFilter !== 'ALL') setCaseFilter('ALL');
  }, [isMultiCaseView, caseFilter]);

  const hasData = nodes.length > 0;

  const updateRelativeMousePos = useCallback((clientX, clientY) => {
    if (!containerRef.current) return;
    const rect = containerRef.current.getBoundingClientRect();
    setMousePos({ x: clientX - rect.left, y: clientY - rect.top });
  }, []);

  const handleNodeMouseEnter = useCallback((event, node) => {
    setHoveredNode(node);
    updateRelativeMousePos(event.clientX, event.clientY);
  }, [updateRelativeMousePos]);

  const handleNodeMouseMove = useCallback((event) => {
    updateRelativeMousePos(event.clientX, event.clientY);
  }, [updateRelativeMousePos]);

  const handleNodeDragStart = useCallback(() => {
    document.body.style.cursor = 'grabbing';
    setHoveredNode(null);
  }, []);

  const handleNodeDragStop = useCallback((event, node) => {
    document.body.style.cursor = '';
    setSelectedNodeInfo(node);
  }, []);

  const handleSpreadLayout = () => {
    const nextStep = spreadStep + 1;
    setSpreadStep(nextStep);
    const factor = nextStep % 3 === 1 ? 1.25 : nextStep % 3 === 2 ? 1.5 : 1.0;
    setNodes((current) => current.map((node) => ({
      ...node,
      position: {
        x: Math.round(node.position.x * factor),
        y: Math.round(node.position.y * (factor > 1 ? 1.1 : 1)),
      },
    })));
    window.setTimeout(() => {
      try { reactFlowInstance.fitView({ padding: 0.2, duration: 300 }); } catch (error) {}
    }, 80);
  };

  const handleResetLayout = () => {
    setCaseFilter('ALL');
    setSpreadStep(0);
    // Reset positions from the latest server payload, not from a stale local
    // array. Changing caseFilter causes the graph-sync effect to re-apply it.
    lastSyncKey.current = '';
    setNodes(sourceNodes.map((node) => ({
      ...node,
      draggable: !isLocked,
      style: { ...node.style, cursor: isLocked ? 'default' : 'grab' },
    })));
    setEdges(sourceEdges);
    window.setTimeout(() => {
      try { reactFlowInstance.fitView({ padding: 0.2, duration: 300 }); } catch (error) {}
    }, 80);
  };

  const toggleLock = () => setIsLocked((current) => !current);

  const getMiniMapNodeColor = (node) => {
    if (node.data?.type === 'case') return '#0284c7';
    if (node.data?.type === 'visual') return '#3b82f6';
    return STATUS_PRESENTATION[getAssessmentStatus(node)].dot;
  };

  const renderNodeTooltip = () => {
    if (!hoveredNode || selectedNodeInfo) return null;
    const width = containerRef.current?.offsetWidth || 800;
    const nearTop = mousePos.y < 125;
    const type = hoveredNode.data?.type;
    const isStatement = type === 'statement';
    const isVisual = type === 'visual';
    const status = getAssessmentStatus(hoveredNode);
    const presentation = STATUS_PRESENTATION[status];
    const left = Math.max(150, Math.min(width - 150, mousePos.x));
    const top = nearTop ? mousePos.y + 18 : mousePos.y - 12;

    return (
      <div
        className="absolute z-50 pointer-events-none drop-shadow-2xl"
        style={{ left: `${left}px`, top: `${top}px`, transform: nearTop ? 'translate(-50%, 0)' : 'translate(-50%, -100%)' }}
      >
        <div className={`p-3 rounded-xl border shadow-2xl backdrop-blur-2xl w-72 sm:w-80 space-y-2 text-xs bg-slate-950/95 ${isStatement ? presentation.border : 'border-blue-500'} text-slate-100`}>
          <div className="flex items-center justify-between pb-1.5 border-b border-slate-800 gap-2">
            <span className="font-mono text-[10px] font-bold uppercase tracking-wider text-slate-400 truncate">
              {isStatement ? 'Statement / assessment' : isVisual ? 'Visual evidence' : 'Forensic case'}
            </span>
            {isStatement && <span className={`text-[10px] font-extrabold px-2 py-0.5 rounded-full border shrink-0 ${presentation.background} ${presentation.text} ${presentation.border}`}>{presentation.label}</span>}
          </div>
          <p className="font-serif italic text-xs text-slate-100 bg-slate-900/90 p-2 rounded-lg border border-slate-800 leading-snug break-words">
            {hoveredNode.data?.full_text || hoveredNode.data?.label || 'No text available.'}
          </p>
          {hoveredNode.data?.case_id && (
            <div className="text-[10px] font-mono text-slate-400 pt-1 border-t border-slate-800/80">
              Case: {hoveredNode.data.case_id}
            </div>
          )}
          {isStatement && Number.isFinite(Number(hoveredNode.data?.sinkhorn_cost)) && (
            <div className="text-[10px] text-slate-500">Sinkhorn divergence diagnostic: {Number(hoveredNode.data.sinkhorn_cost).toFixed(6)}</div>
          )}
        </div>
        <div className={`w-0 h-0 border-l-[6px] border-l-transparent border-r-[6px] border-r-transparent mx-auto ${nearTop ? '-mt-[1px] border-b-[6px] border-b-slate-950' : '-mt-[1px] border-t-[6px] border-t-slate-950'}`} />
      </div>
    );
  };

  return (
    <div className={`flex flex-col h-full space-y-3 ${fullScreenMode ? 'p-6 bg-slate-950 text-slate-100' : ''}`}>
      <div className="flex flex-wrap items-center justify-between gap-3 pb-2 border-b border-slate-700/60">
        <div className="flex items-center gap-2.5">
          <div className={`p-2 rounded-xl ${isMultiCaseView ? 'bg-purple-500/10 border border-purple-500/30 text-purple-400' : 'bg-blue-500/10 border border-blue-500/30 text-blue-400'}`}>
            {isMultiCaseView ? <Network size={20} /> : <GitFork size={20} />}
          </div>
          <div>
            <h3 className="text-base font-black text-slate-100">{isMultiCaseView ? 'Neo4j Multi-Case Relationship Graph' : 'Neo4j Case Knowledge Graph'}</h3>
            <p className="text-[11px] text-slate-400">Classifier assessment labels are shown separately from Sinkhorn diagnostics.</p>
          </div>
        </div>
        <div className="flex items-center gap-2">
          {onRefresh && (
            <button type="button" onClick={onRefresh} className="p-1.5 text-slate-400 hover:text-white rounded-xl bg-slate-900 border border-slate-700 hover:bg-slate-700" title="Refresh graph">
              <RefreshCw size={14} className="text-blue-400" />
            </button>
          )}
          <span className="text-xs px-2.5 py-1 rounded-xl bg-slate-900 border border-slate-700 text-slate-300 font-mono font-bold">{nodes.length} Nodes · {edges.length} Edges</span>
          <button type="button" onClick={toggleFullScreen} className={`flex items-center gap-1.5 text-xs font-semibold px-2.5 py-1.5 rounded-xl border ${fullScreenMode ? 'bg-purple-600 text-white border-purple-500' : 'bg-slate-900 text-slate-300 border-slate-700 hover:bg-slate-700'}`}>
            {fullScreenMode ? <Minimize2 size={14} /> : <Maximize2 size={14} />}
            {fullScreenMode ? 'Exit Fullscreen' : 'Fullscreen'}
          </button>
        </div>
      </div>

      <div className="flex flex-wrap items-center justify-between gap-2 bg-slate-900/90 p-2 rounded-xl border border-slate-700/60 shadow-inner">
        <div className="flex flex-wrap items-center gap-2">
          <button type="button" onClick={toggleLock} className={`flex items-center gap-1.5 text-xs font-semibold px-2.5 py-1.5 rounded-lg border ${isLocked ? 'bg-red-950/80 text-red-200 border-red-700' : 'bg-slate-800 text-slate-200 border-slate-700'}`}>
            {isLocked ? <Lock size={13} className="text-red-400" /> : <Unlock size={13} className="text-emerald-400" />}
            {isLocked ? 'Locked' : 'Lock Graph'}
          </button>
          <button type="button" onClick={handleSpreadLayout} className="flex items-center gap-1.5 text-xs font-semibold px-2.5 py-1.5 rounded-lg bg-slate-800 text-slate-200 border border-slate-700">
            <Move size={13} className="text-purple-400" /> Spread Nodes
          </button>
          <button type="button" onClick={handleResetLayout} className="flex items-center gap-1.5 text-xs font-semibold px-2.5 py-1.5 rounded-lg bg-slate-800 text-slate-200 border border-slate-700">
            <LayoutGrid size={13} className="text-blue-400" /> Reset Layout
          </button>
          {isMultiCaseView && cases.length > 1 && (
            <div className="flex items-center gap-1.5 pl-2 border-l border-slate-700">
              <span className="text-[11px] text-slate-400 font-bold uppercase">Filter:</span>
              <select value={caseFilter} onChange={(event) => setCaseFilter(event.target.value)} className="bg-slate-950 border border-slate-700 rounded-lg px-2 py-1 text-xs text-slate-200">
                <option value="ALL">All cases ({cases.length})</option>
                {cases.map((item) => <option key={item.id} value={item.id}>{item.name || item.id}</option>)}
              </select>
            </div>
          )}
        </div>
        <div className="flex items-center gap-2">
          <span className="text-[10px] px-2.5 py-1 rounded-lg bg-slate-950 text-slate-300 border border-slate-800 font-mono">{hasData ? 'Graph loaded' : 'Awaiting evidence'}</span>
          <span className={`text-[10px] px-2.5 py-1 rounded-lg font-mono border flex items-center gap-1.5 ${isLocked ? 'bg-red-950/80 text-red-300 border-red-800' : 'bg-emerald-950/80 text-emerald-300 border-emerald-800'}`}>
            {isLocked ? <Lock size={11} /> : <Unlock size={11} />}{isLocked ? 'LOCKED' : 'DRAGGABLE'}
          </span>
        </div>
      </div>

      <div
        ref={containerRef}
        onMouseMove={(event) => updateRelativeMousePos(event.clientX, event.clientY)}
        className="w-full rounded-2xl overflow-hidden border border-slate-700/80 bg-slate-950 relative shadow-inner"
        style={{ minHeight: fullScreenMode ? '500px' : '400px', height: fullScreenMode ? 'calc(100vh - 200px)' : '430px' }}
      >
        {!hasData ? (
          <div className="absolute inset-0 flex flex-col items-center justify-center text-center p-6 bg-slate-950/90 z-10 space-y-2">
            <div className="p-3 bg-slate-900 border border-slate-800 rounded-2xl text-slate-500"><UploadCloud size={32} /></div>
            <p className="text-sm font-bold text-slate-300">No Graph Relations Available</p>
            <p className="text-xs text-slate-500 max-w-sm">Create a case and ingest an original image/video with a genuine witness statement to add graph records.</p>
          </div>
        ) : (
          <ReactFlow
            nodes={nodes}
            edges={edges}
            onNodesChange={isLocked ? undefined : onNodesChange}
            onEdgesChange={onEdgesChange}
            onNodeClick={(event, node) => setSelectedNodeInfo(node)}
            onNodeMouseEnter={handleNodeMouseEnter}
            onNodeMouseMove={handleNodeMouseMove}
            onNodeMouseLeave={() => setHoveredNode(null)}
            onNodeDragStart={handleNodeDragStart}
            onNodeDragStop={handleNodeDragStop}
            nodesDraggable={!isLocked}
            nodesConnectable={false}
            elementsSelectable
            selectNodesOnDrag={false}
            fitView
            fitViewOptions={{ padding: 0.25 }}
            minZoom={0.2}
            maxZoom={2}
            attributionPosition="bottom-right"
            style={{ width: '100%', height: '100%', background: '#020617' }}
          >
            <Background color="#1e293b" gap={20} size={1.2} />
            <Controls className="bg-slate-900 fill-slate-300 border border-slate-700 rounded-xl overflow-hidden shadow-xl m-3" />
            {fullScreenMode && (
              <MiniMap
                nodeColor={getMiniMapNodeColor}
                maskColor="rgba(15, 23, 42, 0.75)"
                className="bg-slate-900/90 border border-slate-700 rounded-xl overflow-hidden m-3"
              />
            )}
          </ReactFlow>
        )}

        {renderNodeTooltip()}

        {selectedNodeInfo && (
          <div className="absolute top-4 right-4 bg-slate-900/95 border border-slate-700 p-4 rounded-2xl shadow-2xl max-w-sm text-xs text-slate-300 space-y-2.5 backdrop-blur-md animate-slideIn z-30">
            <div className="flex items-center justify-between text-blue-400 font-bold border-b border-slate-800 pb-1.5">
              <span className="flex items-center gap-1.5"><Info size={14} /> Entity Inspector</span>
              <button type="button" onClick={() => setSelectedNodeInfo(null)} aria-label="Close node inspector" className="text-slate-500 hover:text-white p-0.5 rounded">✕</button>
            </div>
            <div className="space-y-1">
              <span className="text-[10px] text-slate-400 uppercase font-mono block">Content</span>
              <p className="font-serif italic text-white text-xs bg-slate-950 p-2.5 rounded-xl border border-slate-800 leading-snug break-words">
                {selectedNodeInfo.data?.full_text || selectedNodeInfo.data?.label || 'No content available.'}
              </p>
            </div>
            {selectedNodeInfo.data?.type === 'statement' && (() => {
              const status = getAssessmentStatus(selectedNodeInfo);
              const presentation = STATUS_PRESENTATION[status];
              return (
                <div className="flex items-center justify-between gap-2">
                  <span className="text-[10px] text-slate-400 font-mono">Classifier assessment:</span>
                  <span className={`text-[10px] font-bold px-2 py-1 rounded border ${presentation.background} ${presentation.text} ${presentation.border}`}>{presentation.label}</span>
                </div>
              );
            })()}
            {selectedNodeInfo.data?.type === 'statement' && selectedNodeInfo.data?.sinkhorn_cost != null && (
              <div className="flex items-center justify-between text-[10px] text-slate-400 font-mono">
                <span>Sinkhorn diagnostic</span>
                <span>{Number(selectedNodeInfo.data.sinkhorn_cost).toFixed(6)}</span>
              </div>
            )}
            {selectedNodeInfo.data?.case_id && (
              <div className="flex items-center justify-between bg-blue-950/60 p-2 rounded-lg border border-blue-900/80">
                <span className="text-[11px] text-blue-300 font-mono">Case: {selectedNodeInfo.data.case_id}</span>
                {onSelectCase && (
                  <button type="button" onClick={() => { onSelectCase(selectedNodeInfo.data.case_id); setSelectedNodeInfo(null); }} className="text-[10px] px-2 py-0.5 bg-blue-600 hover:bg-blue-500 text-white font-bold rounded-md">Open Case</button>
                )}
              </div>
            )}
            <div className="flex items-center justify-between text-[10px] text-slate-400 font-mono bg-slate-950/80 p-2 rounded-lg border border-slate-800">
              <span className="truncate">Node: {selectedNodeInfo.id}</span>
              <span>({Math.round(selectedNodeInfo.position.x)}, {Math.round(selectedNodeInfo.position.y)})</span>
            </div>
          </div>
        )}
      </div>

      <div className="bg-slate-900/95 border border-slate-700/70 p-3 rounded-xl flex flex-wrap items-center justify-between gap-3 shadow-sm">
        <div className="flex flex-wrap items-center gap-2.5">
          {(['MATCH', 'CONTRADICTION', 'INDETERMINATE']).map((status) => {
            const item = STATUS_PRESENTATION[status];
            return (
              <div key={status} className={`flex items-center gap-2 border px-3 py-1.5 rounded-lg text-xs font-semibold ${item.background} ${item.text} ${item.border}`}>
                <span className="w-2.5 h-2.5 rounded-full" style={{ backgroundColor: item.dot }} />
                {status}
              </div>
            );
          })}
          {isMultiCaseView && (
            <div className="flex items-center gap-2 bg-amber-950/70 border border-amber-800/90 px-3 py-1.5 rounded-lg text-amber-300 text-xs font-semibold">
              <span className="w-2.5 h-2.5 rounded-full bg-amber-400" /> Cross-case relationship
            </div>
          )}
        </div>
        <div className="flex items-center gap-2 bg-slate-950/90 border border-slate-800 px-3 py-1.5 rounded-lg text-slate-300 font-mono text-[11px]">
          <Compass size={13} className={isLocked ? 'text-red-400' : 'text-purple-400'} />
          {isLocked ? 'Graph locked' : 'Drag nodes freely · use Spread Nodes to adjust spacing'}
        </div>
      </div>
    </div>
  );
}

export default function GraphView(props) {
  const [isFullScreen, setIsFullScreen] = useState(false);
  useEffect(() => {
    const handleKeyDown = (event) => {
      if (event.key === 'Escape') setIsFullScreen(false);
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, []);

  const toggleFullScreen = () => setIsFullScreen((current) => !current);

  return (
    <>
      <div className="bg-slate-800/95 backdrop-blur-md p-5 rounded-2xl border border-slate-700/80 shadow-2xl flex flex-col min-h-[580px]">
        <ReactFlowProvider>
          <FlowInner {...props} fullScreenMode={false} toggleFullScreen={toggleFullScreen} />
        </ReactFlowProvider>
      </div>
      {isFullScreen && (
        <div className="fixed inset-0 z-50 bg-slate-950/98 backdrop-blur-2xl p-6 flex flex-col w-screen h-screen animate-fadeIn">
          <ReactFlowProvider>
            <FlowInner {...props} fullScreenMode toggleFullScreen={toggleFullScreen} />
          </ReactFlowProvider>
        </div>
      )}
    </>
  );
}
